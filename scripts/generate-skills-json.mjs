function levels(steps) {
  return steps.map((src) => {
    if (typeof src === "object") return { effect: src.effect, craftTier: src.craftTier ?? null };
    return { effect: src, craftTier: null };
  });
}

function perk(id, name, icon, summary, effectSteps, opts = {}) {
  const req = opts.general
    ? { general: true }
    : { attributeLevels: opts.requires || REQ.combat };
  return {
    id,
    name,
    icon,
    maxLevel: 5,
    requires: req,
    summary,
    ...(opts.catalogPerk ? { catalogPerk: opts.catalogPerk } : {}),
    levels: levels(effectSteps),
  };
}

